"""Python backend.

Produces one module per schema with an IntEnum per enum and a dataclass
per struct. The generated code depends on the small `sigflow.wire` runtime
in python/sigflow, which mirrors the C++ TLV and frame code. Having both
languages generated from the same schema is what allows the system tests
to talk to the C++ binaries from Python.
"""

from __future__ import annotations

from pathlib import Path

from ..model import INT_TYPES, EnumDef, FieldDef, Modifier, Schema, StructDef
from .common import CodeWriter, TypeKind, classify


def output_names(schema: Schema) -> list[str]:
    return [f"{Path(schema.path).stem}_messages.py"]


def generate(schema: Schema) -> dict[str, str]:
    return {output_names(schema)[0]: _Module(schema).render()}


class _Module:
    def __init__(self, schema: Schema) -> None:
        self.schema = schema
        self.out = CodeWriter()

    def render(self) -> str:
        out = self.out
        out.lines(
            f'"""Generated by msgc from {Path(self.schema.path).name}. Do not edit by hand."""',
            "",
            "from __future__ import annotations",
            "",
            "from dataclasses import dataclass, field",
            "from enum import IntEnum",
            "from typing import ClassVar, Optional",
            "",
            "from sigflow import wire",
            "",
        )
        for definition in self.schema.definitions:
            out.line()
            if isinstance(definition, EnumDef):
                self._enum(definition)
            else:
                self._struct(definition)
            out.line()

        out.line()
        out.line("# Lookup table from message id to class, used to decode incoming frames.")
        with out.block("MESSAGES: dict[int, type] = {"):
            for message in self.schema.messages:
                out.line(f"{message.name}.MESSAGE_ID: {message.name},")
        return out.render()

    def _enum(self, enum: EnumDef) -> None:
        with self.out.block(f"class {enum.name}(IntEnum):", None):
            for value in enum.values:
                self.out.line(f"{value.name} = {value.value}")

    def _struct(self, struct: StructDef) -> None:
        out = self.out
        out.line("@dataclass")
        out.line(f"class {struct.name}:")
        with out.indented():
            if struct.is_message:
                out.line(f"MESSAGE_ID: ClassVar[int] = 0x{struct.message_id:04x}")
            out.line(f'NAME: ClassVar[str] = "{struct.name}"')
            out.line()
            for f in struct.fields:
                out.line(f"{f.name}: {self._annotation(f)} = {self._default(f)}")
            if struct.fields:
                out.line()
            self._encode(struct)
            out.line()
            self._decode(struct)

    def _python_type(self, type_name: str) -> str:
        kind = classify(self.schema, type_name)
        return {
            TypeKind.INT: "int",
            TypeKind.BOOL: "bool",
            TypeKind.STRING: "str",
            TypeKind.BYTES: "bytes",
        }.get(kind, type_name)

    def _annotation(self, f: FieldDef) -> str:
        element = self._python_type(f.type_name)
        if f.modifier is Modifier.OPTIONAL:
            return f"Optional[{element}]"
        if f.modifier is Modifier.REPEATED:
            return f"list[{element}]"
        return element

    def _default(self, f: FieldDef) -> str:
        if f.modifier is Modifier.OPTIONAL:
            return "None"
        if f.modifier is Modifier.REPEATED:
            return "field(default_factory=list)"
        kind = classify(self.schema, f.type_name)
        if kind is TypeKind.ENUM:
            enum = self.schema.lookup(f.type_name)
            assert isinstance(enum, EnumDef)
            return f"{enum.name}.{enum.default.name}"
        if kind is TypeKind.STRUCT:
            # Mutable defaults have to go through a factory in dataclasses.
            return f"field(default_factory={f.type_name})"
        return {
            TypeKind.INT: "0",
            TypeKind.BOOL: "False",
            TypeKind.STRING: '""',
            TypeKind.BYTES: 'b""',
        }[kind]

    def _put(self, f: FieldDef, expr: str) -> str:
        kind = classify(self.schema, f.type_name)
        if kind is TypeKind.INT:
            t = INT_TYPES[f.type_name]
            return f"writer.put_int({f.tag}, {expr}, {t.size}, signed={t.signed})"
        if kind is TypeKind.ENUM:
            enum = self.schema.lookup(f.type_name)
            assert isinstance(enum, EnumDef)
            return f"writer.put_int({f.tag}, int({expr}), {INT_TYPES[enum.underlying].size}, signed=False)"
        if kind is TypeKind.BOOL:
            return f"writer.put_bool({f.tag}, {expr})"
        if kind is TypeKind.STRING:
            return f'writer.put_bytes({f.tag}, {expr}.encode("utf-8"))'
        if kind is TypeKind.BYTES:
            return f"writer.put_bytes({f.tag}, {expr})"
        return f"writer.put_bytes({f.tag}, {expr}.encode())"

    def _read(self, f: FieldDef) -> str:
        kind = classify(self.schema, f.type_name)
        if kind is TypeKind.INT:
            t = INT_TYPES[f.type_name]
            return f"wire.read_int(value, {t.size}, signed={t.signed})"
        if kind is TypeKind.ENUM:
            enum = self.schema.lookup(f.type_name)
            assert isinstance(enum, EnumDef)
            return f"wire.read_enum({enum.name}, value, {INT_TYPES[enum.underlying].size})"
        if kind is TypeKind.BOOL:
            return "wire.read_bool(value)"
        if kind is TypeKind.STRING:
            return "wire.read_string(value)"
        if kind is TypeKind.BYTES:
            return "bytes(value)"
        return f"{f.type_name}.decode(value)"

    def _encode(self, struct: StructDef) -> None:
        out = self.out
        with out.block("def encode(self) -> bytes:", None):
            out.line("writer = wire.TlvWriter()")
            for f in struct.fields:
                if f.modifier is Modifier.REQUIRED:
                    out.line(self._put(f, f"self.{f.name}"))
                elif f.modifier is Modifier.OPTIONAL:
                    with out.block(f"if self.{f.name} is not None:", None):
                        out.line(self._put(f, f"self.{f.name}"))
                else:
                    with out.block(f"for item in self.{f.name}:", None):
                        out.line(self._put(f, "item"))
            out.line("return writer.getvalue()")

    def _decode(self, struct: StructDef) -> None:
        out = self.out
        name = struct.name
        out.line("@classmethod")
        with out.block(f"def decode(cls, payload: bytes) -> {name}:", None):
            out.line("message = cls()")
            if not struct.fields:
                out.line(f'wire.parse_tlv(payload, "{name}")  # validates framing only')
                out.line("return message")
                return

            out.line("seen: set[int] = set()")
            with out.block(f'for tag, value in wire.parse_tlv(payload, "{name}"):', None):
                for index, f in enumerate(struct.fields):
                    keyword = "if" if index == 0 else "elif"
                    with out.block(f"{keyword} tag == {f.tag}:", None):
                        with out.block(f'with wire.field_context("{name}.{f.name}"):', None):
                            if f.modifier is not Modifier.REPEATED:
                                out.line("wire.check_duplicate(seen, tag)")
                            if f.modifier is Modifier.REPEATED:
                                out.line(f"message.{f.name}.append({self._read(f)})")
                            else:
                                out.line(f"message.{f.name} = {self._read(f)}")
                out.line("# Any other tag is ignored, the same way the C++ decoder does it.")

            required = [f for f in struct.fields if f.modifier is Modifier.REQUIRED]
            if required:
                with out.block("wire.check_required(seen, {", "})"):
                    for f in required:
                        out.line(f'{f.tag}: "{name}.{f.name}",')
            out.line("return message")
