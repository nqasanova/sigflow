"""C++20 backend.

For every schema two files are produced: a header with the enums and
structs, and a source file with the encode and decode functions. The
generated code leans on the sigflow runtime (TlvWriter::put and
read_value), which picks the wire encoding from the C++ type at compile
time. That keeps this generator free of per type special cases.
"""

from __future__ import annotations

from pathlib import Path

from ..model import INT_TYPES, EnumDef, FieldDef, Modifier, Schema, StructDef
from .common import CodeWriter, TypeKind, classify, pascal_from_upper_snake

_SCALARS = {
    "bool": "bool",
    "string": "std::string",
    "bytes": "sigflow::Bytes",
    **{name: f"std::{'' if t.signed else 'u'}int{t.size * 8}_t" for name, t in INT_TYPES.items()},
}


def output_names(schema: Schema) -> list[str]:
    stem = Path(schema.path).stem
    return [f"{stem}_messages.hpp", f"{stem}_messages.cpp"]


def generate(schema: Schema) -> dict[str, str]:
    header_name, source_name = output_names(schema)
    return {
        header_name: _Header(schema).render(),
        source_name: _Source(schema, header_name).render(),
    }


def enum_constant(name: str) -> str:
    """ACCEPTED -> kAccepted, following the usual style for C++ constants."""
    return "k" + pascal_from_upper_snake(name)


def _element_type(type_name: str) -> str:
    return _SCALARS.get(type_name, type_name)


def _field_type(f: FieldDef) -> str:
    element = _element_type(f.type_name)
    if f.modifier is Modifier.OPTIONAL:
        return f"std::optional<{element}>"
    if f.modifier is Modifier.REPEATED:
        return f"std::vector<{element}>"
    return element


def _banner(schema: Schema) -> list[str]:
    # Only the file name, not the full path, so the output does not change
    # depending on where the build directory lives.
    return [
        f"// Generated by msgc from {Path(schema.path).name}. Do not edit by hand,",
        "// change the schema and rebuild instead.",
    ]


class _Header:
    def __init__(self, schema: Schema) -> None:
        self.schema = schema
        self.out = CodeWriter()

    def render(self) -> str:
        out = self.out
        out.lines(*_banner(self.schema))
        out.lines(
            "#pragma once",
            "",
            "#include <cstdint>",
            "#include <optional>",
            "#include <string>",
            "#include <string_view>",
            "#include <vector>",
            "",
            '#include "sigflow/byte_io.hpp"',
            '#include "sigflow/result.hpp"',
            "",
            f"namespace {'::'.join(self.schema.namespace)} {{",
            "",
        )
        for definition in self.schema.definitions:
            if isinstance(definition, EnumDef):
                self._enum(definition)
            else:
                self._struct(definition)
            out.line()

        out.lines(
            "// Human readable name for a message id of this schema, mostly for logs.",
            "// Returns an empty view for ids that belong to something else.",
            "std::string_view message_name(std::uint16_t id) noexcept;",
            "",
            f"}}  // namespace {'::'.join(self.schema.namespace)}",
        )
        return out.render()

    def _enum(self, enum: EnumDef) -> None:
        out = self.out
        underlying = _SCALARS[enum.underlying]
        with out.block(f"enum class {enum.name} : {underlying} {{", "};"):
            for value in enum.values:
                out.line(f"{enum_constant(value.name)} = {value.value},")
        out.line()

        # A switch over all values. A value that came off the wire can be
        # anything, so the decoder uses this to reject unknown numbers.
        with out.block(f"constexpr bool is_valid({enum.name} value) noexcept {{"):
            with out.block("switch (value) {"):
                for value in enum.values:
                    out.line(f"case {enum.name}::{enum_constant(value.name)}:")
                with out.indented():
                    out.line("return true;")
            out.line("return false;")
        out.line()

        with out.block(f"constexpr std::string_view to_string({enum.name} value) noexcept {{"):
            with out.block("switch (value) {"):
                for value in enum.values:
                    out.line(f'case {enum.name}::{enum_constant(value.name)}: return "{value.name}";')
            out.line('return "<invalid>";')

    def _struct(self, struct: StructDef) -> None:
        out = self.out
        with out.block(f"struct {struct.name} {{", "};"):
            if struct.is_message:
                out.line(f"static constexpr std::uint16_t kMessageId = 0x{struct.message_id:04x};")
            out.line(f'static constexpr std::string_view kName = "{struct.name}";')
            out.line()

            for f in struct.fields:
                out.line(f"{_field_type(f)} {f.name}{self._initializer(f)};")
            if struct.fields:
                out.line()

            out.lines(
                "[[nodiscard]] sigflow::Status encode(sigflow::ByteWriter& out) const;",
                f"static sigflow::Result<{struct.name}> decode(sigflow::ByteView payload);",
                "",
                f"bool operator==(const {struct.name}&) const = default;",
            )

    def _initializer(self, f: FieldDef) -> str:
        if f.modifier is not Modifier.REQUIRED:
            return ""
        kind = classify(self.schema, f.type_name)
        if kind is TypeKind.ENUM:
            enum = self.schema.lookup(f.type_name)
            assert isinstance(enum, EnumDef)
            return f"{{{enum.name}::{enum_constant(enum.default.name)}}}"
        if kind in (TypeKind.INT, TypeKind.BOOL):
            return "{}"
        return ""


class _Source:
    def __init__(self, schema: Schema, header_name: str) -> None:
        self.schema = schema
        self.header_name = header_name
        self.out = CodeWriter()

    def render(self) -> str:
        out = self.out
        ns = "::".join(self.schema.namespace)
        out.lines(*_banner(self.schema))
        out.lines(
            f'#include "{self.header_name}"',
            "",
            '#include "sigflow/tlv.hpp"',
            "",
            f"namespace {ns} {{",
            "",
        )
        for struct in self.schema.structs:
            self._encode(struct)
            out.line()
            self._decode(struct)
            out.line()

        with out.block("std::string_view message_name(std::uint16_t id) noexcept {"):
            with out.block("switch (id) {"):
                for message in self.schema.messages:
                    out.line(f"case {message.name}::kMessageId: return {message.name}::kName;")
            out.line("return {};")
        out.line()
        out.line(f"}}  // namespace {ns}")
        return out.render()

    def _encode(self, struct: StructDef) -> None:
        out = self.out
        # An empty struct never touches its argument, the comment keeps the
        # unused parameter warning quiet without a cast.
        param = "out" if struct.fields else "/*out*/"
        with out.block(f"sigflow::Status {struct.name}::encode(sigflow::ByteWriter& {param}) const {{"):
            if struct.fields:
                out.line("sigflow::TlvWriter writer(out);")
            for f in struct.fields:
                if f.modifier is Modifier.REQUIRED:
                    out.line(f"SIGFLOW_TRY(writer.put({f.tag}, {f.name}));")
                elif f.modifier is Modifier.OPTIONAL:
                    with out.block(f"if ({f.name}.has_value()) {{"):
                        out.line(f"SIGFLOW_TRY(writer.put({f.tag}, *{f.name}));")
                else:
                    with out.block(f"for (const auto& item : {f.name}) {{"):
                        out.line(f"SIGFLOW_TRY(writer.put({f.tag}, item));")
            out.line("return sigflow::Status::success();")

    def _decode(self, struct: StructDef) -> None:
        out = self.out
        name = struct.name
        required = [f for f in struct.fields if f.modifier is Modifier.REQUIRED]

        with out.block(f"sigflow::Result<{name}> {name}::decode(sigflow::ByteView payload) {{"):
            out.line("auto fields = sigflow::parse_tlv(payload);")
            out.line(f'if (!fields) return std::move(fields).error().with_context("{name}");')
            out.line()
            out.line(f"{name} message;")
            for f in required:
                out.line(f"bool has_{f.name} = false;")
            out.line()

            with out.block("for (const sigflow::TlvField& field : *fields) {"):
                with out.block("switch (field.tag) {"):
                    for f in struct.fields:
                        self._decode_case(struct, f)
                    out.line("default:")
                    with out.indented():
                        out.line("// Unknown tag, most likely a field added by a newer peer.")
                        out.line("break;")
            out.line()

            for f in required:
                out.line(f"if (!has_{f.name}) {{")
                with out.indented():
                    out.line(f'return sigflow::make_error(sigflow::Errc::missing_field, "{name}.{f.name}");')
                out.line("}")
            out.line("return message;")

    def _decode_case(self, struct: StructDef, f: FieldDef) -> None:
        out = self.out
        where = f"{struct.name}.{f.name}"
        element = _element_type(f.type_name)

        with out.block(f"case {f.tag}: {{"):
            duplicate = {
                Modifier.REQUIRED: f"has_{f.name}",
                Modifier.OPTIONAL: f"message.{f.name}.has_value()",
            }.get(f.modifier)
            if duplicate:
                with out.block(f"if ({duplicate}) {{"):
                    out.line(f'return sigflow::make_error(sigflow::Errc::duplicate_field, "{where}");')

            out.line(f"auto value = sigflow::read_value<{element}>(field);")
            out.line(f'if (!value) return std::move(value).error().with_context("{where}");')
            if f.modifier is Modifier.REPEATED:
                out.line(f"message.{f.name}.push_back(std::move(*value));")
            else:
                out.line(f"message.{f.name} = std::move(*value);")
            if f.modifier is Modifier.REQUIRED:
                out.line(f"has_{f.name} = true;")
            out.line("break;")
